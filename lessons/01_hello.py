# บทที่ 1: โปรแกรมแรกของเรา
# บรรทัดที่ขึ้นต้นด้วย # คือ "คอมเมนต์" — คอมพิวเตอร์จะข้ามไป ไม่ทำงาน

# print() ใช้แสดงข้อความออกทางหน้าจอ
print("สวัสดีชาวโลก!")

# ตัวแปร (variable) คือกล่องเก็บข้อมูล
name = "NWC"          # ข้อความ (string) ต้องอยู่ในเครื่องหมายคำพูด
age = 15              # ตัวเลขจำนวนเต็ม (int)

print("ชื่อของฉันคือ", name)
print("อีก 5 ปี ฉันจะอายุ", age + 5, "ปี")
